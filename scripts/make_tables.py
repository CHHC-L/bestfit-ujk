"""Build the result tables from the *verified* CSVs written by scripts/verify_all.py.

Writes results/SUMMARY.md (counts, the classification grid, row completeness, one line per certified
pair) and, if REPORT.md exists, refreshes its <!-- TABLE --> / <!-- ROWS --> blocks.

Grid legend: L / B = linear / bounded waste, new (this work); l* / b* = known before and re-proved here;
l / b = known before (CJSW93 computer proofs, the CCGJMSWY91 theorem for k >= j(j+3)/2, KRS98 for
j = k-2), not re-proved; S = Theta(sqrt n) (j = k-1); ? = open; . = trivially bounded (j <= 2).
usage: make_tables.py [--kmax 25] [--jrows 13]
"""
import argparse
import csv
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# CJSW93 Table 2 (k <= 14): left open ('x') were the pairs below; linear proved: (8,11), (9,12); every
# other pair with k <= 14, j <= k-2 was proved bounded (computer proof or their Theorem 1).
CJSW93_OPEN = {(8, 12), (8, 13), (9, 11), (9, 13), (9, 14), (10, 12), (10, 13), (10, 14), (11, 13),
               (11, 14), (12, 14)}
CJSW93_LINEAR = {(8, 11), (9, 12)}


def earlier(j, k):
    """Status before this work: S, ., b, l or ? (open)."""
    if j == k - 1:
        return "S"
    if j <= 2:
        return "."
    if j == k - 2:                      # Kenyon-Rabani-Sinclair 1998
        return "b"
    if 2 * k >= j * (j + 3):            # Coffman et al. 1991
        return "b"
    if k <= 14 and (j, k) not in CJSW93_OPEN:
        return "l" if (j, k) in CJSW93_LINEAR else "b"
    return "?"


def load(name):
    p = os.path.join(ROOT, "results", name)
    if not os.path.exists(p):
        sys.exit(f"missing results/{name}: run scripts/verify_all.py first")
    return list(csv.DictReader(open(p)))


def status(cls, j, k):
    """Final status: L/B/l*/b* from our certificates, else the earlier status."""
    r = cls.get((j, k))
    e = earlier(j, k)
    if r:
        o = "L" if r["result"] == "linear" else "B"
        if e in ("l", "b") and e.upper() != o:
            sys.exit(f"certificate for ({j},{k}) contradicts the literature ({e})")
        return o if e == "?" else o.lower() + "*"
    return e


def grid(cls, kmin, kmax):
    jmax = kmax - 1
    out = ["| k \\ j | " + " | ".join(str(j) for j in range(1, jmax + 1)) + " |", "|---" * (jmax + 1) + "|"]
    for k in range(kmin, kmax + 1):
        row = []
        for j in range(1, jmax + 1):
            s = status(cls, j, k) if j < k else ""
            row.append(f"**{s}**" if s in ("L", "B") else s)
        out.append(f"| {k} | " + " | ".join(row) + " |")
    out.append("\n**L**/**B**: new (this work); l/b: known before; l*/b*: known and re-proved here; "
               "S: Theta(sqrt n); ?: open; .: trivially bounded (j <= 2).")
    return "\n".join(out)


def rows_summary(cls, jmax):
    """Row-wise completeness: every k from j+2 up to the CCGJMSWY91 threshold must be settled."""
    out = ["| j | linear k (all k ≥ j+2) | certified/known up to | theorem from k = | row complete |",
           "|---|---|---|---|---|"]
    for j in range(3, jmax + 1):
        thr = (j * (j + 3) + 1) // 2           # smallest k with 2k >= j(j+3)
        lin, missing = [], []
        for k in range(j + 2, thr):
            s = status(cls, j, k)
            if s == "?":
                missing.append(k)
            elif s.lower().startswith("l"):
                lin.append(k)
        span = f"{min(lin)}–{max(lin)}" if lin else "none"
        if lin and len(lin) != max(lin) - min(lin) + 1:
            span = ",".join(map(str, lin))
        miss = "yes" if not missing else ("missing " + ",".join(map(str, missing[:8])) +
                                          ("…" if len(missing) > 8 else ""))
        out.append(f"| {j} | {span} | {thr - 1} | {thr} | {miss} |")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kmax", type=int, default=25)
    ap.add_argument("--jrows", type=int, default=13)
    a = ap.parse_args()
    cls = {(int(r["j"]), int(r["k"])): r for r in load("classification.csv")}
    struct = {(int(r["j"]), int(r["k"])): r for r in load("structure.csv")}
    rates = {(int(r["j"]), int(r["k"])): r for r in load("rates.csv")}
    ver = load("verification.csv")

    npy = sum(r["python"] == "CERTIFIED" for r in ver)
    new = [x for x in cls if earlier(*x) == "?"]
    rep = [x for x in cls if earlier(*x) != "?"]
    nl = sum(cls[x]["result"] == "linear" for x in new)
    open_pairs = [(j, k) for k in range(5, a.kmax + 1) for j in range(3, k - 1) if status(cls, j, k) == "?"]
    lines = ["# Summary of certified results (generated by scripts/make_tables.py)", "",
             f"* certificates verified by both exact C++ verifiers (bfcert, verify2): "
             f"{sum(r['status'] == 'OK' for r in ver)} of {len(ver)}"
             + (f"; also by the Python verifier: {npy}" if npy else
                " (`make verify-py` adds the Python verifier)"),
             f"* pairs open before and now settled: **{len(new)}** ({nl} linear, {len(new) - nl} bounded); "
             f"k ≤ {a.kmax}: {sum(1 for x in new if x[1] <= a.kmax)}",
             f"* previously known results re-proved: {len(rep)}",
             f"* structure certificates (Theorem C, waste = gap-1 bins + O(1)): {len(struct)}",
             f"* certified rate brackets (Theorem D): {len(rates)}",
             f"* still open for k ≤ {a.kmax}: " + (", ".join(f"({j},{k})" for j, k in open_pairs) or "none"),
             "", "| (j,k) | result | before | certificate | patterns | certified drift | structure (C) |",
             "|---|---|---|---|---|---|---|"]
    for (j, k) in sorted(cls, key=lambda t: (t[1], t[0])):
        r = cls[(j, k)]
        before = {"?": "open", "b": "bounded", "l": "linear"}.get(earlier(j, k), earlier(j, k))
        st = "yes" if (j, k) in struct else ("-" if r["result"] == "bounded" else "no")
        lines.append(f"| ({j},{k}) | {r['result']} | {before} | `{r['certificate']}` | {r['patterns']} | "
                     f"{float(r['drift']):.4g} | {st} |")
    lines += ["", "## Grid (k ≤ %d)" % a.kmax, "", grid(cls, 5, a.kmax), "",
              "## Rows (complete for all k when every k below the theorem threshold is settled)", "",
              rows_summary(cls, a.jrows)]
    open(os.path.join(ROOT, "results", "SUMMARY.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines[:9]))

    rep_path = os.path.join(ROOT, "REPORT.md")
    if not os.path.exists(rep_path):
        return 0
    s = open(rep_path).read()
    s = re.sub(r"<!-- TABLE -->.*?<!-- /TABLE -->",
               lambda m: "<!-- TABLE -->\n" + grid(cls, 5, a.kmax) + "\n<!-- /TABLE -->", s, flags=re.S)
    s = re.sub(r"<!-- ROWS -->.*?<!-- /ROWS -->",
               lambda m: "<!-- ROWS -->\n" + rows_summary(cls, a.jrows) + "\n<!-- /ROWS -->", s, flags=re.S)
    nok = sum(r["status"] == "OK" for r in ver)
    s = re.sub(r"<!-- NCERT -->.*?<!-- /NCERT -->", f"<!-- NCERT -->{nok}<!-- /NCERT -->", s, flags=re.S)
    open(rep_path, "w").write(s)
    return 0


if __name__ == "__main__":
    sys.exit(main())
